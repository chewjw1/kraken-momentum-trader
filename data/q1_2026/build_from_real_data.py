def split_daily_to_4h(daily_rows):
    """Convert daily OHLC to 6 x 4h candles, distributing the range realistically."""
    candles_4h = []
    for date_str, d_open, d_high, d_low, d_close in daily_rows:
        dt = datetime.strptime(date_str, "%Y-%m-%d").replace(tzinfo=timezone.utc)
        # 6 sub-candles per day
        prices = [d_open]
        for i in range(5):
            t = (i + 1) / 6
            mid = d_open + t * (d_close - d_open)
            noise = (d_high - d_low) * 0.08 * random.gauss(0, 1)
            prices.append(max(d_low, min(d_high, mid + noise)))
        prices.append(d_close)

        for i in range(6):
            ts = dt + timedelta(hours=4 * i)
            o = prices[i]
            c = prices[i + 1]
            h = max(o, c) + abs(random.gauss(0, 1)) * (d_high - d_low) * 0.15
            l = min(o, c) - abs(random.gauss(0, 1)) * (d_high - d_low) * 0.15
            h = min(h, d_high)
            l = max(l, d_low)
            h = max(h, o, c)
            l = min(l, o, c)
            vol = 500 + abs(random.gauss(0, 200))
            candles_4h.append((int(ts.timestamp()), round(o, 2), round(h, 2),
                               round(l, 2), round(c, 2), round(vol, 2)))
    return candles_4h


def interpolate_4h(anchors, vol_daily, start_date, end_date):
    """Interpolate anchor prices to 4h candles with realistic noise."""
    anchor_dts = []
    anchor_prices = []
    for ds, price in anchors:
        dt = datetime.strptime(ds, "%Y-%m-%d").replace(tzinfo=timezone.utc)
        anchor_dts.append(dt.timestamp())
        anchor_prices.append(math.log(price))

    candles = []
    dt = start_date
    while dt <= end_date:
        ts = dt.timestamp()
        # Log-linear interpolation
        for i in range(len(anchor_dts) - 1):
            if anchor_dts[i] <= ts <= anchor_dts[i + 1]:
                t = (ts - anchor_dts[i]) / (anchor_dts[i + 1] - anchor_dts[i])
                log_price = anchor_dts[i] and (
                    anchor_prices[i] + t * (anchor_prices[i + 1] - anchor_prices[i])
                )
                break
        else:
            if ts < anchor_dts[0]:
                log_price = anchor_prices[0]
            else:
                log_price = anchor_prices[-1]

        trend_price = math.exp(log_price)
        noise = random.gauss(0, vol_daily * 0.4)
        c = trend_price * math.exp(noise)
        intra = trend_price * vol_daily * 0.5
        o = c * math.exp(random.gauss(0, vol_daily * 0.2))
        h = max(o, c) + abs(random.gauss(0, 1)) * intra
        l = min(o, c) - abs(random.gauss(0, 1)) * intra
        h = max(h, o, c)
        l = min(l, o, c)
        vol = 1e5 * (c / 1000) * (1 + abs(random.gauss(0, 0.3)))
        candles.append((int(dt.timestamp()), round(o, 6), round(h, 6),
                        round(l, 6), round(c, 6), round(vol, 2)))
        dt += timedelta(hours=4)
    return candles


def write_csv(filepath, rows):
    with open(filepath, "w", newline="") as f:
        w = csv.writer(f)
        for row in rows:
            w.writerow(row)


